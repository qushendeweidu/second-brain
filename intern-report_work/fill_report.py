def fill_cell(cell, lines):
    """将单元格内容替换为 lines（多段落），保留第一个段落格式，正文仿宋14pt。"""
    tc = cell._tc
    ps = tc.findall(qn('w:p'))
    if not ps:
        return
    tmpl = ps[0]
    for r in tmpl.findall(qn('w:r')):
        tmpl.remove(r)
    for p in ps[1:]:
        tc.remove(p)
    prev = tmpl
    for i, line in enumerate(lines):
        p = tmpl if i == 0 else copy.deepcopy(tmpl)
        if i > 0:
            prev.addnext(p)
            prev = p
        r = p.makeelement(qn('w:r'), {})
        rPr = r.makeelement(qn('w:rPr'), {})
        rFonts = rPr.makeelement(qn('w:rFonts'), {})
        rFonts.set(qn('w:ascii'), '仿宋')
        rFonts.set(qn('w:hAnsi'), '仿宋')
        rFonts.set(qn('w:eastAsia'), '仿宋')
        rPr.append(rFonts)
        sz = rPr.makeelement(qn('w:sz'), {})
        sz.set(qn('w:val'), '28')
        rPr.append(sz)
        szCs = rPr.makeelement(qn('w:szCs'), {})
        szCs.set(qn('w:val'), '28')
        rPr.append(szCs)
        r.append(rPr)
        t = r.makeelement(qn('w:t'), {})
        t.text = line
        t.set(qn('xml:space'), 'preserve')
        r.append(t)
        p.append(r)

def set_keywords(cell, text):
    """替换关键词行第二个 run 的占位文字。"""
    tc = cell._tc
    for r in tc.iter(qn('w:r')):
        for t in r.findall(qn('w:t')):
            if '关键词1' in (t.text or ''):
                t.text = text
                return True
    return False

